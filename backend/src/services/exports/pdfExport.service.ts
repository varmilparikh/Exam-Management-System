import PDFDocument from "pdfkit";

import type { PDFReportOptions } from "../../types/pdf.js";

class PDFExportService {
  async generatePDF<T extends object>(
    options: PDFReportOptions<T>,
  ): Promise<Buffer> {
    return new Promise((resolve, reject) => {
      const doc = new PDFDocument({
        size: "A4",
        layout: "landscape",
        margin: 40,
      });

      const chunks: Buffer[] = [];

      doc.on("data", (chunk: Buffer) => chunks.push(chunk));

      doc.on("end", () => {
        resolve(Buffer.concat(chunks));
      });

      doc.on("error", reject);

      const pageLeft = doc.page.margins.left;
      const pageRight = doc.page.margins.right;
      const pageTop = doc.page.margins.top;
      const pageBottom = doc.page.margins.bottom;
      // Keep the footer readable while reclaiming the extra margin space that
      // previously pushed a short final row onto its own page.
      const tableBottom = doc.page.height - pageBottom + 12;

      const usablePageWidth = doc.page.width - pageLeft - pageRight;

      // --------------------------------------------------
      // Calculate column widths
      // --------------------------------------------------

      const configuredWidths = options.columns.map(
        (column) => column.width ?? 100,
      );

      const totalConfiguredWidth = configuredWidths.reduce(
        (sum, width) => sum + width,
        0,
      );

      const widthScale =
        totalConfiguredWidth > usablePageWidth
          ? usablePageWidth / totalConfiguredWidth
          : 1;

      const columnWidths = options.columns.map((column, index) => {
        const configuredWidth = configuredWidths[index] ?? 100;

        return configuredWidth * widthScale;
      });

      // --------------------------------------------------
      // Helpers
      // --------------------------------------------------

      const getCellWidth = (index: number): number =>
        columnWidths[index] ?? 100;

      const getTextWidth = (index: number) =>
        Math.max(getCellWidth(index) - 8, 20);

      const getRowHeight = (row: T | null, includeHeader = false) => {
        const heights = options.columns.map((column, index) => {
          const rawValue = includeHeader
            ? column.title
            : row
              ? String(row[column.id] ?? "")
              : "";

          return doc.heightOfString(rawValue, {
            width: getTextWidth(index),
            align: column.align ?? "left",
            lineGap: 1,
          });
        });

        return Math.max(...heights, 12) + 10;
      };

      // --------------------------------------------------
      // Title
      // --------------------------------------------------

      doc
        .font("Helvetica-Bold")
        .fontSize(20)
        .fillColor("black")
        .text(options.title, {
          align: "center",
        });

      if (options.subtitle) {
        doc
          .moveDown(0.5)
          .font("Helvetica")
          .fontSize(12)
          .text(options.subtitle, {
            align: "center",
          });
      }

      doc.moveDown(1.5);

      // --------------------------------------------------
      // Metadata
      // --------------------------------------------------

      doc.font("Helvetica").fontSize(9);

      if (options.generatedBy) {
        doc.text(`Generated By : ${options.generatedBy}`);
      }

      const generatedOn = new Intl.DateTimeFormat("en-IN", {
        dateStyle: "medium",
        timeStyle: "short",
      }).format(new Date());

      doc.text(`Generated On : ${generatedOn}`);

      doc.moveDown(1.5);

      // --------------------------------------------------
      // Table
      // --------------------------------------------------

      let currentY = doc.y;

      const drawTableHeader = () => {
        const headerHeight = getRowHeight(null, true);

        let currentX = pageLeft;

        doc.font("Helvetica-Bold").fontSize(8).fillColor("black");

        options.columns.forEach((column, index) => {
          const width = getCellWidth(index);

          doc.rect(currentX, currentY, width, headerHeight).stroke();

          doc.text(column.title, currentX + 4, currentY + 5, {
            width: width - 8,
            align: column.align ?? "center",
            lineGap: 1,
          });

          currentX += width;
        });

        return headerHeight;
      };

      let headerHeight = drawTableHeader();

      currentY += headerHeight;

      // --------------------------------------------------
      // Footer
      // --------------------------------------------------

      let pageNumber = 1;

      const drawFooter = () => {
        const footerY = doc.page.height - 25;

        doc
          .font("Helvetica")
          .fontSize(8)
          .fillColor("gray")
          .text("Exam Management System", pageLeft, footerY, {
            width: usablePageWidth,
            align: "center",
          });

        doc.text(`Page ${pageNumber}`, pageLeft, footerY, {
          width: usablePageWidth,
          align: "right",
        });

        doc.fillColor("black");
      };

      // --------------------------------------------------
      // Rows
      // --------------------------------------------------

      doc.font("Helvetica").fontSize(8).fillColor("black");

      options.rows.forEach((row) => {
        const rowHeight = getRowHeight(row);

        // Create a new page when the current row won't fit.
        if (currentY + rowHeight > tableBottom) {
          drawFooter();

          doc.addPage();

          pageNumber += 1;

          currentY = pageTop;

          headerHeight = drawTableHeader();
          currentY += headerHeight;

          doc.font("Helvetica").fontSize(8).fillColor("black");
        }

        let currentX = pageLeft;

        options.columns.forEach((column, index) => {
          const width = getCellWidth(index);

          const value = String(row[column.id] ?? "");

          doc.rect(currentX, currentY, width, rowHeight).stroke();

          doc.text(value, currentX + 4, currentY + 5, {
            width: width - 8,
            align: column.align ?? "left",
            lineGap: 1,
          });

          currentX += width;
        });

        currentY += rowHeight;
      });

      drawFooter();

      doc.end();
    });
  }
}

export default new PDFExportService();
